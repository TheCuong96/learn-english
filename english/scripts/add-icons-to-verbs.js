// Default emoji for verbs that don't have a specific mapping
const defaultIcon = '⚡';

// Read the original verbs-data.json
const dataPath = path.join(__dirname, '..', 'public', 'data', 'verbs-data.json');
const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));

// Add icon to each verb
const updatedData = data.map(verb => {
  const verbWord = verb.word.toLowerCase();
  const icon = verbIcons[verbWord] || defaultIcon;
  
  return {
    ...verb,
    icon: icon
  };
});

// Save the updated data
fs.writeFileSync(dataPath, JSON.stringify(updatedData, null, 2), 'utf8');

