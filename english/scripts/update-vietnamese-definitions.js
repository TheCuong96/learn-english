// Read the verbs-data.json
const dataPath = path.join(__dirname, '..', 'public', 'data', 'verbs-data.json');
const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));

// Update Vietnamese definitions
const updatedData = data.map(verb => {
  const verbWord = verb.word.toLowerCase().trim();
  let newDefinition = vietnameseDefinitions[verbWord];
  
  // Try exact match first, then try removing spaces and parentheses
  if (!newDefinition) {
    const cleanWord = verbWord.split('(')[0].trim();
    newDefinition = vietnameseDefinitions[cleanWord];
  }
  
  // Fallback to original definition if no mapping found
  if (!newDefinition) {
    newDefinition = verb.definition || '';
  }
  
  return {
    ...verb,
    definition: newDefinition
  };
});

// Save the updated data
fs.writeFileSync(dataPath, JSON.stringify(updatedData, null, 2), 'utf8');

